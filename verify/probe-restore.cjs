const { chromium } = require('playwright-core');
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const logs = [];
  page.on('console', (m) => { const t = m.text(); if (t.includes('sess-restore')) logs.push(t); });
  page.on('pageerror', (e) => logs.push('PAGEERROR: ' + String(e).slice(0, 200)));
  await page.goto('http://localhost:8904/', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => document.body && document.body.innerText.length > 50, null, { timeout: 120000 });
  await page.waitForTimeout(3000);
  console.log('LOGS-AFTER-FRESH-LOAD:', logs.length ? logs : 'none');
  await page.evaluate(() => window.__NAV__ && window.__NAV__.goGuest('Login'));
  await page.waitForTimeout(1200);
  const inputs = page.locator('input');
  await inputs.nth(0).fill('restoreprobe');
  await inputs.nth(1).fill('9999');
  await page.getByText('Sign In', { exact: true }).click({ timeout: 15000 });
  await page.waitForTimeout(3000);
  const b1 = await page.evaluate(() => document.body.innerText.slice(0, 60).replace(/\n/g, ' | '));
  console.log('BEFORE-RELOAD:', b1);
  logs.length = 0;
  await page.reload({ waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => document.body && document.body.innerText.length > 50, null, { timeout: 120000 });
  await page.waitForTimeout(5000);
  const b2 = await page.evaluate(() => document.body.innerText.slice(0, 60).replace(/\n/g, ' | '));
  console.log('AFTER-RELOAD:', b2);
  console.log('LOGS-AFTER-RELOAD:', logs.length ? logs : 'none');
  await browser.close();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
