export function tOf(key: string, lang?: Lang): string {
  const e = STR[key];
  if (!e) return key;
  return (lang ?? current) === 'en' ? e.en : e.id;
}

/** Alias tOf untuk impor bernama tr di titik yang butuh tanpa hook. */
export const tr = tOf;

export function useLang(): {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
} {
  const [, bump] = useState(0);
  useEffect(() => {
    let alive = true;
    const fn = () => {
      if (alive) bump((x) => x + 1);
    };
    listeners.add(fn);
    // Pulihkan pilihan bahasa terakhir dari storage (default Inggris bila belum ada).
    void getItem(LS_LANG).then((v) => {
      if (!alive) return;
      if ((v === 'id' || v === 'en') && v !== current) {
        current = v;
        bump((x) => x + 1);
      }
    });
    return () => {
      alive = false;
      listeners.delete(fn);
    };
  }, []);
  return { lang: current, setLang, t: (k: string) => tOf(k) };
}
