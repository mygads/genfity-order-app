/**
 * Kamus dwibahasa minimal (ID/EN) untuk layar area
 * history - esb - kitchen - member - voucher - topup - cancel.
 * Bahasa default mengikuti prinsip produk: notifikasi sistem dan
 * email transaksional default Inggris, dan default locale UI adalah
 * Inggris (en); pengguna bisa beralih via useLang().setLang().
 */
import { useEffect, useState } from 'react';
import { getItem, setItem } from './storage';

export type Lang = 'id' | 'en';

/** Kunci persist bahasa di storage. Default Inggris; Indonesia bila pengguna memilih ID. */
const LS_LANG = 'genfity.lang';

let current: Lang = 'en';
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  // Persist pilihan bahasa agar dipakai lagi setelah restart (fire-and-forget).
  void setItem(LS_LANG, next).catch(() => undefined);
  listeners.forEach((fn) => {
    try {
      fn();
    } catch {
      /* abaikan */
    }
  });
}

